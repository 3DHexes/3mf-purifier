const DICT = { en, pl, de, fr, es };

// Poza Windows nie ma Eksploratora, który pokazuje okładki 3MF.
const NOT_WIN = !/^win/i.test(window.NL_OS || 'Windows');
if (NOT_WIN) for (const d of Object.values(DICT)) if (d['th.hintNoWin']) d['th.hint'] = d['th.hintNoWin'];
let lang = 'en';

export function setLang(l) { lang = DICT[l] ? l : 'en'; return lang; }
export function getLang() { return lang; }
export function locale() { return DICT[lang].locale; }

export function t(key, params) {
  const v = DICT[lang][key] ?? en[key] ?? key;
  if (typeof v === 'function') return v(params);
  if (!params || typeof params !== 'object') return v;
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

// Tłumaczenie błędu/ostrzeżenia z kodem (z silnika czyszczenia).
export function tCode(prefix, item) {
  if (!item) return '';
  if (typeof item === 'string') return item;
  const key = `${prefix}.${item.code}`;
  if (item.code && (en[key] !== undefined)) return t(key, item.params || {});
  return t('e.unknown', { message: item.message || item.code || '' });
}

// Statyczne teksty w HTML: data-i18n (tekst), data-i18n-html, data-i18n-title, data-i18n-aria.
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.documentElement.lang = lang;
}
